func loadPrev(root, profile string) (map[string]string, error) {
	data, err := os.ReadFile(filepath.Join(root, "deploy", profile, ".env"))
	if errors.Is(err, os.ErrNotExist) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, err
	}
	return parseEnv(string(data)), nil
}

func parseEnv(data string) map[string]string {
	values := map[string]string{}
	for _, line := range strings.Split(data, "\n") {
		line = strings.TrimSpace(strings.TrimRight(line, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok || key == "" {
			continue
		}
		values[key] = value
	}
	return values
}

func writeProfile(root string, in answers) error {
	dir := filepath.Join(root, "deploy", in.Profile)
	secrets := filepath.Join(dir, "secrets")
	if err := os.MkdirAll(secrets, 0o700); err != nil {
		return err
	}
	envText, err := formatEnv(root, in)
	if err != nil {
		return err
	}
	files := map[string]string{
		filepath.Join(dir, ".env"):                       envText,
		filepath.Join(secrets, "postgres_password"):      in.PostgresPassword + "\n",
		filepath.Join(secrets, "rabbitmq.conf"):          rabbitConfig(in),
		filepath.Join(secrets, "rustfs_access_key"):      in.RustFSAccessKey + "\n",
		filepath.Join(secrets, "rustfs_secret_key"):      in.RustFSSecretKey + "\n",
		filepath.Join(secrets, "initial_admin_password"): in.AdminPassword + "\n",
	}
	if in.S3Provider != "rustfs" && in.S3PathStyle {
		files[filepath.Join(secrets, "s3_access_key")] = in.S3AccessKey + "\n"
		files[filepath.Join(secrets, "s3_secret_key")] = in.S3SecretKey + "\n"
	}
	for path, contents := range files {
		if err := writePrivate(path, []byte(contents)); err != nil {
			return err
		}
	}
	return nil
}

func formatEnv(root string, in answers) (string, error) {
	mode, err := tenancyMode(in.Profile)
	if err != nil {
		return "", err
	}
	postgresDSN, err := postgresDSN(in)
	if err != nil {
		return "", err
	}
	rabbitURL, err := rabbitURL(in)
	if err != nil {
		return "", err
	}
	lines := []string{
		"# Generated by go run ./cmd/setup.",
		"# Secrets stay in this file until --rotate-secrets.",
		"TENANCY_MODE=" + mode,
		"HTTP_PORT=" + strconv.Itoa(in.HTTPPort),
		"POSTGRES_PORT=" + strconv.Itoa(in.PostgresPort),
		"POSTGRES_DB=" + in.PostgresDB,
		"POSTGRES_USER=" + in.PostgresUser,
		"POSTGRES_PASSWORD=" + in.PostgresPassword,
		"POSTGRES_DSN=" + postgresDSN,
		"RABBITMQ_PORT=" + strconv.Itoa(in.RabbitPort),
		"RABBITMQ_MANAGEMENT_PORT=" + strconv.Itoa(in.RabbitManagementPort),
		"RABBITMQ_USER=" + in.RabbitUser,
		"RABBITMQ_PASSWORD=" + in.RabbitPassword,
		"RABBITMQ_URL=" + rabbitURL,
		"S3_ENDPOINT=" + in.S3Endpoint,
		"S3_REGION=" + in.S3Region,
		"S3_BUCKET=" + in.S3Bucket,
		"S3_ACCESS_KEY=" + in.S3AccessKey,
		"S3_SECRET_KEY=" + in.S3SecretKey,
		"S3_PATH_STYLE=" + strconv.FormatBool(in.S3PathStyle),
		"S3_PROVIDER=" + in.S3Provider,
		"RUSTFS_ACCESS_KEY=" + in.RustFSAccessKey,
		"RUSTFS_SECRET_KEY=" + in.RustFSSecretKey,
	}
	harpyLines, err := harpyEnvLines(root, in)
	if err != nil {
		return "", err
	}
	lines = append(lines, harpyLines...)
	return strings.Join(lines, "\n") + "\n", nil
}

func postgresDSN(in answers) (string, error) {
	return serviceURL("postgres", in.PostgresUser, in.PostgresPassword, in.PostgresPort, "/"+in.PostgresDB, "sslmode=disable")
}

func rabbitURL(in answers) (string, error) {
	return serviceURL("amqp", in.RabbitUser, in.RabbitPassword, in.RabbitPort, "/", "")
}

func serviceURL(scheme, user, password string, port int, path, rawQuery string) (string, error) {
	if strings.ContainsAny(user+password, "\r\n") {
		return "", errors.New("credential contains a newline")
	}
	parsed := url.URL{
		Scheme:   scheme,
		User:     url.UserPassword(user, password),
		Host:     net.JoinHostPort("127.0.0.1", strconv.Itoa(port)),
		Path:     path,
		RawQuery: rawQuery,
	}
	return parsed.String(), nil
}

func rabbitConfig(in answers) string {
	return fmt.Sprintf("default_user = %s\ndefault_pass = %s\n", in.RabbitUser, in.RabbitPassword)
}

func writePrivate(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		_ = os.Remove(tmp)
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}
