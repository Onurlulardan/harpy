package config

func privilegedKeys(dsnKey, receiptKey string) []string {
	return []string{
		"HARPY_ENVIRONMENT", "HARPY_POSTGRES_ENDPOINT_KIND",
		dsnKey, dsnKey + "_FILE", "HARPY_POSTGRES_CONNECT_TIMEOUT",
		"HARPY_POSTGRES_CLEANUP_TIMEOUT", "HARPY_LOG_LEVEL",
		"HARPY_RELEASE_MANIFEST_PATH", "HARPY_RELEASE_SIGNATURE_PATH",
		"HARPY_RELEASE_TRUST_ROOT_PATH",
		"HARPY_BOOTSTRAP_AUTHORITY_MANIFEST_PATH",
		"HARPY_BOOTSTRAP_AUTHORITY_SIGNATURE_PATH",
		"HARPY_CREDENTIAL_LEASE_ID", receiptKey,
		"HARPY_ATTESTATION_SIGNING_KEY", "HARPY_ATTESTATION_SIGNING_KEY_FILE",
	}
}

func clusterBootstrapKeys() []string {
	keys := privilegedKeys("HARPY_BOOTSTRAP_MAINTENANCE_DSN", "HARPY_BOOTSTRAP_RECEIPT_PATH")
	return append(
		keys,
		"HARPY_BOOTSTRAP_TARGET_DSN", "HARPY_BOOTSTRAP_TARGET_DSN_FILE",
		"HARPY_ROLES_MANIFEST_PATH", "HARPY_PRIVILEGES_MANIFEST_PATH",
		"HARPY_OWNERSHIP_MANIFEST_PATH", "HARPY_BOOTSTRAP_OPERATION_PATH",
	)
}

func extensionArtifactKeys() []string {
	return []string{
		"HARPY_EXTENSION_MANIFEST_PATH", "HARPY_OWNERSHIP_MANIFEST_PATH",
		"HARPY_EXTENSION_OPERATION_PATH",
	}
}
