func TestIssueCatalogReturnsCopy(t *testing.T) {
	t.Parallel()
	catalog := IssueCodes()
	catalog[0] = "CHANGED"
	if IssueCodes()[0] != IssueArityMismatch {
		t.Fatal("issue catalog exposed mutable storage")
	}
}
