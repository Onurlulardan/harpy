package main

import (
	"strings"
	"testing"
)

func TestInspectAllowsBudgetAndSkippedFiles(t *testing.T) {
	root := t.TempDir()
	for _, name := range []string{
		"create.go", "seed.sql", "README.md", "config.yaml", "run.sh", "run.ps1",
	} {
		writeFixture(t, root, name, repeatLines("line", maxLines))
	}
	writeFixture(t, root, "Dockerfile", "FROM scratch\n")
	writeFixture(t, root, "vendor/service.go", repeatLines("line", maxLines+1))
	writeFixture(t, root, "node_modules/common.go", "package common\n")
	writeFixture(t, root, "pkg/build/rules.go", "package rules\n")
	for _, name := range []string{"go.sum", "yarn.lock", "package-lock.json", "pnpm-lock.yaml", "Cargo.lock"} {
		writeFixture(t, root, name, "\xff"+repeatLines("line", maxLines+1))
	}
	writeFixture(t, root, "wide.json", `{"value":"`+strings.Repeat("a", 80*1024)+`"}`)
	if violations := inspectFixture(t, root); len(violations) != 0 {
		t.Fatalf("allowed tree rejected: %v", violations)
	}
}

func TestInspectAllowsGeneratedFileOverBudget(t *testing.T) {
	root := t.TempDir()
	content := "// Code generated by test. DO NOT EDIT.\n" + repeatLines("line", maxLines+1)
	writeFixture(t, root, "currency_gen.go", content)
	writeManifest(t, root, "currency_gen.go", content)
	if violations := inspectFixture(t, root); len(violations) != 0 {
		t.Fatalf("generated file rejected: %v", violations)
	}
}

func TestInspectAllowsRegisteredZip(t *testing.T) {
	root := t.TempDir()
	content := "PK\x03\x04\x00binary"
	writeFixture(t, root, "out/bundle.zip", content)
	writeManifest(t, root, "out/bundle.zip", content)
	if violations := inspectFixture(t, root); len(violations) != 0 {
		t.Fatalf("registered zip rejected: %v", violations)
	}
}
